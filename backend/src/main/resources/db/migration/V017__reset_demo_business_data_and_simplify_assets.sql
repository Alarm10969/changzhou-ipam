CREATE TABLE asset_definition (
  id INTEGER PRIMARY KEY,
  asset_type TEXT NOT NULL CHECK(asset_type IN ('TECH','NON_TECH')),
  name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 100),
  requires_user INTEGER NOT NULL DEFAULT 0 CHECK(requires_user IN (0,1)),
  requires_resource_code INTEGER NOT NULL DEFAULT 0 CHECK(requires_resource_code IN (0,1)),
  recommended_range_type TEXT NOT NULL CHECK(recommended_range_type IN ('PRODUCTION','NETWORK_MANAGEMENT','EXTENSION','MONITORING','TEST','OFFICE')),
  is_active INTEGER NOT NULL DEFAULT 1 CHECK(is_active IN (0,1)),
  deleted_at TEXT,
  created_by INTEGER REFERENCES sys_user(id) ON DELETE RESTRICT,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE UNIQUE INDEX uk_asset_definition_visible ON asset_definition(asset_type,name) WHERE deleted_at IS NULL;
CREATE INDEX idx_asset_definition_select ON asset_definition(asset_type,is_active,deleted_at,name);

DROP TABLE ip_application;
CREATE TABLE ip_application (
  id INTEGER PRIMARY KEY,
  applicant_user_id INTEGER NOT NULL REFERENCES sys_user(id) ON DELETE RESTRICT,
  applicant_name TEXT NOT NULL CHECK(length(applicant_name) BETWEEN 1 AND 100),
  applicant_username TEXT,
  unified_auth_id TEXT NOT NULL CHECK(length(unified_auth_id) BETWEEN 1 AND 64),
  branch_id INTEGER NOT NULL REFERENCES branch(id) ON DELETE RESTRICT,
  outlet_id INTEGER NOT NULL REFERENCES outlet(id) ON DELETE RESTRICT,
  asset_id INTEGER NOT NULL REFERENCES asset_definition(id) ON DELETE RESTRICT,
  asset_type TEXT NOT NULL CHECK(asset_type IN ('TECH','NON_TECH')),
  asset_name TEXT NOT NULL CHECK(length(asset_name) BETWEEN 1 AND 100),
  requires_user INTEGER NOT NULL CHECK(requires_user IN (0,1)),
  requires_resource_code INTEGER NOT NULL CHECK(requires_resource_code IN (0,1)),
  asset_code TEXT,
  user_name TEXT,
  user_unified_auth_id TEXT,
  recommended_range_type TEXT NOT NULL CHECK(recommended_range_type IN ('PRODUCTION','NETWORK_MANAGEMENT','EXTENSION','MONITORING','TEST','OFFICE')),
  final_range_type TEXT,
  status TEXT NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED')),
  rejection_reason TEXT,
  approval_opinion TEXT,
  reviewed_by INTEGER REFERENCES sys_user(id) ON DELETE RESTRICT,
  reviewed_at TEXT,
  version INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  CHECK((requires_user=1 AND user_name IS NOT NULL AND user_unified_auth_id IS NOT NULL) OR (requires_user=0 AND user_name IS NULL AND user_unified_auth_id IS NULL)),
  CHECK((requires_resource_code=1 AND asset_code IS NOT NULL) OR (requires_resource_code=0 AND asset_code IS NULL)),
  CHECK((status='REJECTED' AND rejection_reason IS NOT NULL) OR status<>'REJECTED')
);
CREATE INDEX idx_ip_application_owner_time ON ip_application(applicant_user_id,created_at);
CREATE INDEX idx_ip_application_pending ON ip_application(status,branch_id,created_at) WHERE status='PENDING';
CREATE INDEX idx_ip_application_asset ON ip_application(asset_id,recommended_range_type,final_range_type);

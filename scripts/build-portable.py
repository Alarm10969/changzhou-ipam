#!/usr/bin/env python3
"""Java 11 offline build, smoke tests and Kylin delivery on macOS/Linux/Windows."""
import argparse
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import sys
import zipfile
from datetime import datetime, timedelta, timezone

ROOT = Path(__file__).resolve().parents[1]
SMOKES = [
    "StageOneSmokeTest", "StageTwoSmokeTest", "StageThreeSmokeTest",
    "StageFourBaselineSmokeTest", "StageFiveRemediationSmokeTest",
    "StageSixLegacyUpgradeSmokeTest", "StageSevenSoftDeleteReuseSmokeTest",
    "StageEightBranchUserReuseSmokeTest", "StageNinePhaseFourSmokeTest",
    "StageTenPlanningOverlapSmokeTest", "StageElevenManualAssignmentGatewaySmokeTest",
    "StageTwelveV019UpgradeSmokeTest", "StageThirteenMacAddressSmokeTest",
    "StageFourteenResourceMaintenanceSmokeTest", "StageFifteenBackupRestoreSmokeTest",
]


def run(argv):
    subprocess.run([str(x) for x in argv], cwd=ROOT, check=True)


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest() if hasattr(hashlib, "file_digest") else hashlib.sha256(stream.read()).hexdigest()


def manifest_line(name, value):
    text = name + ": " + value
    lines = []
    while len(text) > 70:
        lines.append(text[:70])
        text = " " + text[70:]
    lines.append(text)
    return "\r\n".join(lines) + "\r\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--java-home", type=Path)
    parser.add_argument("--test", action="store_true")
    parser.add_argument("--http-test", action="store_true", help="Run real HTTP integration checks against an isolated database")
    parser.add_argument("--package", action="store_true")
    args = parser.parse_args()
    suffix = ".exe" if os.name == "nt" else ""
    java_bin = args.java_home / "bin" if args.java_home else None
    def java_tool(name):
        found = java_bin / (name + suffix) if java_bin else shutil.which(name)
        if not found:
            raise RuntimeError("A JDK with Java 11 support is required: " + name)
        return found
    libs = sorted((ROOT / "backend/lib").glob("*.jar"))
    for line in (ROOT / "backend/dependencies.sha256").read_text().splitlines():
        if not line.strip():
            continue
        expected, relative = line.split(None, 1)
        path = ROOT / "backend" / relative.strip()
        if digest(path).lower() != expected.lower():
            raise RuntimeError("Offline dependency checksum mismatch: " + path.name)
    print("PASS|OFFLINE_DEPENDENCIES", flush=True)
    out = ROOT / ".local-v025-build"
    marker = out / ".ipam-generated"
    if out.exists():
        if not marker.is_file():
            raise RuntimeError("Refusing to overwrite an unmanaged build directory: " + str(out))
        shutil.rmtree(out)
    out.mkdir()
    marker.write_text("Generated by scripts/build-portable.py\n")
    classes = out / "classes"
    classes.mkdir()
    classpath = os.pathsep.join(str(x) for x in libs)
    sources = sorted((ROOT / "backend/src/main/java").rglob("*.java"))
    sources += sorted((ROOT / "backend/src/test/java").rglob("*.java"))
    run([java_tool("javac"), "--release", "11", "-encoding", "UTF-8", "-cp", classpath, "-d", classes, *sources])
    shutil.copytree(ROOT / "backend/src/main/resources", classes, dirs_exist_ok=True)
    print("PASS|JAVA11_COMPILE", flush=True)
    if args.test:
        for name in SMOKES:
            run([java_tool("java"), "-cp", str(classes) + os.pathsep + classpath,
                 "com.icbc.changzhou.ipam." + name])
        print("PASS|ALL_SMOKE_TESTS", flush=True)
    if args.http_test:
        run([sys.executable, ROOT / "scripts/http-v025-regression.py", "--java-home",
             Path(java_tool("java")).resolve().parent.parent, "--classes", classes])
    release = out / "package"
    release.mkdir()
    for folder in ["lib", "frontend", "samples", "deploy"]:
        source = ROOT / "backend/lib" if folder == "lib" else ROOT / folder
        shutil.copytree(source, release / folder, ignore=shutil.ignore_patterns("dist"))
    shutil.copytree(ROOT / "docs/release", release / "docs")
    shutil.copy2(ROOT / "docs/requirements-v025-2026-10-09.md", release / "docs")
    for file in ["README.md", "VERSION.txt"]:
        shutil.copy2(ROOT / file, release / file)
    shutil.copy2(ROOT / "backend/dependencies.sha256", release / "dependencies.sha256")
    manifest = out / "MANIFEST.MF"
    manifest.write_bytes((manifest_line("Manifest-Version", "1.0") +
                         manifest_line("Main-Class", "com.icbc.changzhou.ipam.IpamApplication") +
                         manifest_line("Class-Path", " ".join("lib/" + x.name for x in libs)) + "\r\n").encode("ascii"))
    run([java_tool("jar"), "cfm", release / "ipam-stage3.jar", manifest, "-C", classes, "."])
    checksum = release / "release-files.sha256"
    files = sorted(x for x in release.rglob("*") if x.is_file())
    checksum.write_bytes("".join(digest(x) + "  " + x.relative_to(release).as_posix() + "\n" for x in files).encode("ascii"))
    print("PASS|SELF_CONTAINED_RELEASE|" + str(release), flush=True)
    if args.package:
        delivery = ROOT / "deliverables"
        delivery.mkdir(exist_ok=True)
        stamp = datetime.now(timezone(timedelta(hours=8))).strftime("%Y%m%d-%H%M%S")
        target = delivery / ("ipam-stage4-v025-resource-maintenance-kylin-arm64-" + stamp + ".zip")
        with zipfile.ZipFile(target, "x", zipfile.ZIP_DEFLATED) as archive:
            for file in sorted(x for x in release.rglob("*") if x.is_file()):
                archive.write(file, file.relative_to(release).as_posix())
        with zipfile.ZipFile(target) as archive:
            for line in archive.read("release-files.sha256").decode("ascii").splitlines():
                expected, name = line.split("  ", 1)
                if "\\" in name or hashlib.sha256(archive.read(name)).hexdigest() != expected:
                    raise RuntimeError("Delivery verification failed: " + name)
        print("PASS|DELIVERY|" + str(target), flush=True)
        print("SHA256|" + digest(target), flush=True)


if __name__ == "__main__":
    main()
